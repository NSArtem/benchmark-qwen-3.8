"""A10: regenerate RESULTS.md from results/*/summary.json."""

from __future__ import annotations

import json
from pathlib import Path

STAGE10 = Path(__file__).resolve().parents[1]
COLUMNS = (
    "exp_id", "status", "recipe", "GiB", "bpw", "Δnll all", "Δnll en", "Δnll code", "Δnll ru",
    "top1 all", "kl_top32 all", "decode tok/s 4K", "decode tok/s 16K", "decode tok/s 32K",
    "peak GiB 16K", "min distinct4", "P2 ok", "P4 ok",
)


def _fmt(value, digits=4) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def row(summary: dict) -> list[str]:
    ev = summary.get("eval") or {}
    ck = summary.get("checkpoint") or {}
    ladder = {r["ctx"]: r for r in summary.get("ladder") or []}
    gen = {g["id"]: g for g in summary.get("gen_check") or []}

    def e(part, key):
        return (ev.get(part) or {}).get(key)

    distinct = [g["distinct4"] for g in gen.values()]
    return [
        summary["exp_id"],
        summary["status"],
        summary["recipe"],
        _fmt(ck.get("gib"), 3),
        _fmt(ck.get("bpw"), 3),
        _fmt(e("all", "delta_nll")),
        _fmt(e("en", "delta_nll")),
        _fmt(e("code", "delta_nll")),
        _fmt(e("ru", "delta_nll")),
        _fmt(e("all", "top1_agree")),
        _fmt(e("all", "kl_top32")),
        _fmt((ladder.get(4096) or {}).get("decode_tok_s"), 2),
        _fmt((ladder.get(16384) or {}).get("decode_tok_s"), 2),
        _fmt((ladder.get(32768) or {}).get("decode_tok_s"), 2),
        _fmt((ladder.get(16384) or {}).get("peak_mlx_gib"), 2),
        _fmt(min(distinct), 3) if distinct else "—",
        _fmt((gen.get("P2") or {}).get("p2_has_187")),
        _fmt((gen.get("P4") or {}).get("p4_json_valid")),
    ]


def render(summaries: list[dict]) -> str:
    lines = [
        "# Stage 10 results",
        "",
        "Generated by `uv run python -m stage10.make_table`. Do not edit.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "| " + " | ".join("---" for _ in COLUMNS) + " |",
    ]
    for summary in sorted(summaries, key=lambda s: s["exp_id"]):
        lines.append("| " + " | ".join(row(summary)) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    summaries = [json.loads(p.read_text()) for p in sorted((STAGE10 / "results").glob("*/summary.json"))]
    (STAGE10 / "RESULTS.md").write_text(render(summaries), encoding="utf-8")
    print(f"{len(summaries)} summaries")


if __name__ == "__main__":
    main()
